# cp4_05_hmi_page_pattern.py - หลักการ 4.5: หน้าจอแผงควบคุม (HMI) แถบสถานะเห็นตลอด คำสั่งอันตรายต้องยืนยัน
#
# หลักการ  : แผงควบคุมที่ดีมี 4 กฎ
#            1) แถบสถานะอยู่ "นอก" แท็บ จึงเห็นทุกหน้า: ปั๊มเดินไหม · น้ำในถังเท่าไร · ไฟเตือน
#            2) แยกหน้าตามงาน: ภาพรวม (ดูอย่างเดียว) · สั่งงาน (ปุ่ม) · บันทึก (ย้อนดูว่าเกิดอะไร)
#            3) คำสั่งอันตราย (เปิดปั๊ม) ต้องยืนยันก่อน และกล่องต้องบอกว่ากำลังจะเกิดอะไร
#               ส่วน "หยุด" ทำทันที ไม่ถาม เพราะการหยุดปลอดภัยเสมอ
#            4) ทุกเหตุการณ์ลงบันทึกพร้อมเวลา และมีเสียงหนึ่งครั้ง
#            โค้ดแยก 3 หน้าที่: build() สร้างจอครั้งเดียว · update() ส่งไปจอเฉพาะที่เปลี่ยน
#            · handle() รับเหตุการณ์ แปลด้วยตาราง (id, type) เป็นคำสั่ง แล้วให้สมองตัดสิน
# ลองเล่น  : แตะแท็บ "สั่งงาน" แล้วแตะ "เปิดปั๊ม" กล่องยืนยันโผล่ แตะ "ยืนยัน" = ปั๊มเดิน
#            "ยกเลิก" = ไม่เดิน · แตะ "หยุด" = หยุดทันที
#            หมุน VR2 (น้ำในถัง) ลงต่ำกว่า 20 % ไฟเตือนติด ปั๊มหยุดเอง และสั่งเปิดไม่ได้จนน้ำกลับมาถึง 25 %
#            เปิดแท็บ "บันทึก" ดูลำดับเหตุการณ์ (ครบ 6 แถวแล้ววนทับแถวที่เก่าที่สุด)
# ของบนบอร์ด: จอสัมผัส · ลูกบิด VR2 (น้ำในถัง) · ลำโพง (เสียงหนึ่งครั้งต่อหนึ่งเหตุการณ์)
# ในฟาร์ม  : จอหน้าตู้ปั๊มที่ใครเดินผ่านก็อ่านสถานะได้ทันที คนแตะพลาดไม่ทำให้ปั๊มเดินแห้ง
#            และหัวหน้าย้อนดูได้ว่าเกิดอะไรเมื่อไร
# บอร์ด    : TESAIoT Dev Kit และ BENTO Emulator
#            ปุ่มที่เติมเข้า MsgBox ด้วย add_button() ไม่ส่งเหตุการณ์กลับมาให้ Python ทั้งบนบอร์ดและ Emulator
#            (เฟิร์มแวร์ผูก clicked ไว้กับ ui.Button เท่านั้น) ไฟล์นี้จึงใช้ MsgBox แสดงคำถาม
#            แล้ววาง ui.Button จริงสองปุ่มทับไว้ในกล่องเป็นคำตอบ
#            กล่องนี้ไม่ได้ล็อกทั้งจอ แท็บกับปุ่ม "หยุด" ยังแตะได้ระหว่างที่กล่องเปิดอยู่

import pots
import time
import ui

# ---- 1) ตั้งค่า (แก้ได้) ----
TANK_MIN = 20        # น้ำในถังต่ำกว่านี้ (%) = ไฟเตือน + ปั๊มหยุดเอง + ห้ามเปิด
TANK_HYST = 5        # ช่องกันกระพือ: ต้องขึ้นมาถึง TANK_MIN + 5 จึงหายเตือน (ลูกบิดไม่แกว่งเข้าออก)
LOG_ROWS = 6         # บันทึกกี่แถว (ครบแล้ววนทับแถวที่เก่าที่สุด)
TAB_BAR_H = 44       # ความสูงแถบแท็บ (พิกเซล) ต้องสูงพอให้นิ้วแตะได้
LOOP_MS = 30         # ดึงเหตุการณ์จากจอทุกกี่ ms (คิวบนจอจุ 16 เต็มแล้วทิ้งของใหม่)
TICK_MS = 500        # อ่านลูกบิดทุกกี่ ms (ตัวเลขบนจอจึงเปลี่ยนไม่ถี่กว่านี้)
RUN_MS = 180000      # เล่นนาน 3 นาทีแล้วจบเอง
SPEAKER = 40             # ความดังลำโพงรวม 0-100% (ใช้ได้กับ firmware 2.4.2 ขึ้นไป)
VOLUME = 25              # ความดังเสียง 0-127 (≈20%) ใช้กับทุกเสียงในไฟล์นี้
BTN_NAMES = ("SW5", "SW6")   # ชื่อบนแผง: SW5 = ปุ่มล่าง, SW6 = ปุ่มบน (ไฟล์นี้ใช้จอสัมผัสแทน)

COL_TEXT, COL_DIM = 0xE8EAED, 0x9AA3AF
COL_OK, COL_BAD, COL_INFO = 0x30A46C, 0xE5484D, 0x4A9EFF


# ---- 2) ฮาร์ดแวร์ ----
def tank_percent():
    return pots.read(1) * 100 // 4095      # VR2: น้ำในถัง 0-100 %


# เสียงเตือนใช้ ui.tone เพราะปรับความดังได้ (ui.sfx ในเฟิร์มแวร์นี้ปรับความดังไม่ได้)
TUNES = {"tap": (76,), "start": (72, 79), "stop": (79, 72), "good": (72, 79, 84),
         "bad": (84, 76), "empty": (84, 76, 69), "hit": (88,)}


def beep(name):
    for n in TUNES[name]:
        ui.tone(n, ui.WAVE_SINE, VOLUME, 90)
        time.sleep_ms(100)


# ---- 3) สมอง (ตัดสินใจ) ไม่แตะฮาร์ดแวร์ ----
# สถานะทั้งหมดอยู่ใน dict เดียว s จอเป็นแค่ "ภาพ" ของ s ไม่ใช่ที่เก็บสถานะ
# s["ask"] = กำลังถามยืนยันอยู่ไหม · s["low"] = ถังต่ำ (เตือน) · s["tab"] = แท็บที่เปิดดูอยู่
# ทุกอย่างที่เปลี่ยน s ผ่านประตูเดียวนี้: ทั้งคำสั่งจากจอ และค่าถังที่อ่านทุก TICK_MS
def decide(s, cmd, v):
    # คืน (ข้อความลงบันทึก, ชื่อเสียง) หรือ None = ไม่มีอะไรต้องบันทึก
    if cmd == "tank":
        s["tank"] = v
        low = v < TANK_MIN + (TANK_HYST if s["low"] else 0)
        if low == s["low"]:
            return None                        # สถานะเดิม ไม่มีเหตุการณ์ใหม่
        s["low"] = low
        if not low:
            return ("น้ำพอ", "good")
        s["ask"] = s["pump"] = False           # ถังต่ำ: ปั๊มหยุดเอง และปิดกล่องที่ถามอยู่
        return ("ถังต่ำ ปั๊มหยุด", "empty")
    if cmd == "tab":
        s["tab"] = v                           # Tabview ส่ง value_changed พร้อมลำดับแท็บ (เริ่มที่ 0)
        return None
    if cmd == "stop":
        s["ask"] = s["pump"] = False           # หยุด ชนะทุกอย่าง ไม่ต้องถาม
        return ("หยุดปั๊ม", "stop")
    if cmd == "open":
        if s["low"]:
            return ("ถังต่ำ ห้ามเปิด", "bad")  # กฎความปลอดภัยอยู่ที่สมอง ไม่ถามด้วยซ้ำ
        s["ask"] = True                        # ยังไม่ทำ แค่เปิดกล่องถาม
        return ("ถามยืนยัน", "tap")
    if cmd and s["ask"]:                       # "yes" / "no" นับเฉพาะตอนกล่องเปิดอยู่
        s["ask"] = False
        if cmd == "yes":
            s["pump"] = True
            return ("เปิดปั๊ม", "start")
        return ("ยกเลิก", "tap")
    return None                                # เหตุการณ์ที่ไม่อยู่ในตาราง หรือคำตอบที่มาช้า


# ---- 4) เครือข่าย (ไฟล์นี้ไม่ใช้) ----


# ---- 5) หน้าจอ ----
def build():
    # สร้างทุกอย่างครั้งเดียว คืน dict ของ widget ที่ต้องใช้ภายหลัง (ใช้ 18 จาก 64 ที่เฟิร์มแวร์มีให้)
    ui.screen()
    time.sleep_ms(200)
    w = {}
    # แถบสถานะ: สร้างบนจอ ไม่ใช่ในแท็บ จึงเห็นทุกหน้า (ของที่ต้องเห็นตลอดห้ามซ่อนในแท็บ)
    w["pled"] = ui.Led(x=12, y=8, w=28, h=28, color=COL_OK, value=0)
    w["pump"] = ui.Label(" ", x=50, y=10, color=COL_TEXT, value=20)
    w["tank"] = ui.Label(" ", x=240, y=10, color=COL_TEXT, value=20)
    w["alarm"] = ui.Led(x=440, y=8, w=28, h=28, color=COL_BAD, value=0)
    ui.Label("เตือน", x=478, y=10, color=COL_DIM, value=20)
    # แท็บ จบที่ y=338 เพราะมุมขวาล่างเป็นปุ่ม Console ของเฟิร์มแวร์
    tabs = ui.Tabview(x=12, y=52, w=768, h=286, value=TAB_BAR_H)
    w["tabs"] = tabs
    # add_tab() คืน "หน้า" ของแท็บนั้น ของที่อยู่ในหน้าใส่ parent= หน้านั้น
    # พิกัดของมันนับจากมุมซ้ายบนของหน้า ไม่ใช่ของจอ
    tab = tabs.add_tab("ภาพรวม")
    # Bar ที่สูงกว่ากว้าง = แท่งแนวตั้ง เติมจากล่างขึ้นบน หน้าตาเหมือนถังน้ำ
    # (ไม่ใช้ Arc เพราะ Arc ลากด้วยนิ้วได้ หน้า "ดูอย่างเดียว" ต้องไม่มีของที่แตะแล้วค่าเพี้ยน)
    w["lvl"] = ui.Bar(x=0, y=0, w=70, h=200, min=0, max=100, value=0, parent=tab)
    w["big"] = ui.Label(" ", x=100, y=80, color=COL_TEXT, value=28, parent=tab)
    tab = tabs.add_tab("สั่งงาน")
    w["open"] = ui.Button("เปิดปั๊ม", x=0, y=0, w=220, h=80, color=COL_INFO, parent=tab)
    w["stop"] = ui.Button("หยุด", x=0, y=100, w=220, h=80, color=COL_BAD, parent=tab)
    tab = tabs.add_tab("บันทึก")
    log = ui.Table(cols=2, rows=LOG_ROWS + 1, x=0, y=0, w=600, h=230, parent=tab)
    log.col_width(1, 470)                       # คอลัมน์ 0 (เวลา) ใช้ความกว้างตั้งต้น 130 พิกเซล
    log.add_row("เวลา", "เหตุการณ์")            # แถว 0 = หัวตาราง  add_row เขียนแถวถัดไปให้เอง
    w["log"] = log
    # กล่องยืนยัน: สร้างหลังแท็บ จึงลอยอยู่บนแท็บ ปุ่มคำตอบสร้างหลังกล่อง จึงอยู่บนกล่อง
    # ซ่อนไว้ก่อน update() โชว์เมื่อ s["ask"] เป็น True  ข้อความ: บรรทัดแรก = หัวกล่อง ที่เหลือ = เนื้อความ
    # บอกสิ่งที่จะเกิด ไม่ใช่ถามลอย ๆ ว่า "แน่ใจไหม" (ระดับน้ำดูได้จากแถบสถานะที่เห็นตลอด)
    box = ui.MsgBox("เปิดปั๊ม?\nปั๊มจะเดินทันที", x=300, y=100, w=440, h=210)
    yes = ui.Button("ยืนยัน", x=320, y=226, w=190, h=64, color=COL_OK)
    no = ui.Button("ยกเลิก", x=530, y=226, w=190, h=64, color=COL_DIM)
    box.hide()
    yes.hide()
    no.hide()
    w["box"], w["yes"], w["no"] = box, yes, no
    w["help"] = ui.Label(" ", x=12, y=352, color=COL_DIM, value=16)   # บรรทัดล่าง: ใช้บอก "จบรอบ"
    ui.poll()
    return w


def changed(seen, key, v):
    # จอโชว์ค่านี้อยู่แล้วไหม ถ้ายัง: จำค่าใหม่ แล้วตอบ True (ให้ส่งไปจอ)
    if seen.get(key) == v:
        return False
    seen[key] = v
    return True


def update(w, s, seen):
    # ส่งสถานะ s ไปจอเฉพาะส่วนที่เปลี่ยน (seen = สิ่งที่จอโชว์อยู่ตอนนี้)
    if changed(seen, "pump", s["pump"]):
        w["pled"].value(int(s["pump"]))                   # Led: 0 = หรี่ (ไม่ดับมืด), 1 = สว่าง
        w["pump"].text("ปั๊มเดิน" if s["pump"] else "ปั๊มหยุด")
    t = s["tank"]
    if changed(seen, "tank", t):
        w["tank"].text("ถัง %d %%" % t)
    if changed(seen, "low", s["low"]):
        w["alarm"].value(int(s["low"]))
    if s["tab"] == 0 and changed(seen, "lvl", t):         # หน้าภาพรวม: อัปเดตเฉพาะตอนเปิดดูอยู่
        w["lvl"].value(t)
        w["big"].text("น้ำในถัง (VR2) %d %%" % t)
    if changed(seen, "ask", s["ask"]):
        for k in ("box", "yes", "no"):
            w[k].show() if s["ask"] else w[k].hide()


def log(w, s, entry):
    # หนึ่งเหตุการณ์ = หนึ่งแถวในบันทึก + เสียงหนึ่งครั้ง (entry = None: ไม่มีอะไรต้องบันทึก)
    if not entry:
        return
    text, tune = entry
    tb, n = w["log"], s["n"]
    t = "%d วิ" % (time.ticks_diff(time.ticks_ms(), s["t0"]) // 1000)
    if n < LOG_ROWS:
        tb.add_row(t, text)
    else:
        r = 1 + n % LOG_ROWS                              # ครบแล้ว: ทับแถวที่เก่าที่สุด ด้วย cell(แถว, คอลัมน์, ข้อความ)
        tb.cell(r, 0, t)
        tb.cell(r, 1, text)
    s["n"] = n + 1
    beep(tune)


def handle(w, s, router, ev):
    # เหตุการณ์หนึ่งใบ -> ตาราง (id, type) -> คำสั่ง -> สมองตัดสิน -> บันทึก
    # ไม่อยู่ในตาราง = cmd เป็น None สมองจึงไม่ทำอะไร
    log(w, s, decide(s, router.get((ev["handle"], ev["type"])), ev["value"]))


# ---- 6) โปรแกรมหลัก ----
def main():
    if hasattr(ui, "volume"):    # บอร์ดที่ยังเป็น 2.4.1 ข้ามบรรทัดนี้
        ui.volume(SPEAKER)
    w = build()
    router = {                                            # ตาราง (id ของ widget, ชนิดเหตุการณ์) -> คำสั่งที่สมองรู้จัก
        (w["open"].id(), "clicked"): "open",
        (w["yes"].id(), "clicked"): "yes",
        (w["no"].id(), "clicked"): "no",
        (w["stop"].id(), "clicked"): "stop",
        (w["tabs"].id(), "value_changed"): "tab",
    }
    tank = tank_percent()
    s = {"pump": False, "tank": tank, "low": tank < TANK_MIN, "ask": False, "tab": 0,
         "n": 0, "t0": time.ticks_ms()}
    seen = {}
    t_tick = s["t0"]
    while time.ticks_diff(time.ticks_ms(), s["t0"]) < RUN_MS:
        evs = ui.poll()                                   # 1) ฟัง: ดึงจนคิวว่าง (ครั้งละ <= 8)
        while evs:
            for ev in evs:
                handle(w, s, router, ev)                  # 2) ตาราง -> สมอง -> บันทึก
            evs = ui.poll()
        if time.ticks_diff(time.ticks_ms(), t_tick) >= TICK_MS:
            t_tick = time.ticks_ms()
            log(w, s, decide(s, "tank", tank_percent()))  # อ่าน VR2 ผ่านประตูเดียวกัน
        update(w, s, seen)                                # 3) โชว์เฉพาะที่เปลี่ยน
        time.sleep_ms(LOOP_MS)
    s["ask"] = s["pump"] = False                          # จบรอบ: ปั๊มหยุด กล่องปิด
    update(w, s, seen)
    w["help"].color(COL_BAD)
    w["help"].text("จบรอบแล้ว - กด Program to Device อีกครั้งเพื่อเล่นใหม่")
    ui.poll()


main()

# ----- ตาคุณ แก้แล้วรันใหม่ -----
# 1) เดาก่อนรัน: อยู่แท็บ "บันทึก" แล้วหมุน VR2 ลงต่ำกว่า 20 % แถบสถานะด้านบนยังบอกไหมว่าถังต่ำ
#    ถ้าย้ายไฟเตือนเข้าไปไว้ในแท็บ "ภาพรวม" (ใส่ parent=tab) คนที่ยืนดูแท็บอื่นอยู่จะรู้ไหม
# 2) แก้ข้อความในกล่องเป็น "แน่ใจไหม?" เฉย ๆ แล้วเทียบว่าแบบไหนทำให้คนหยุดคิดก่อนกด
#    แล้วลองให้ "หยุด" ต้องยืนยันด้วย: ตอนน้ำจะล้น การถามก่อนหยุดช่วยหรือทำร้าย
# 3) เพิ่ม "หมดเวลา": ถามแล้วไม่มีใครตอบใน 8 วิ = ปิดกล่อง ไม่เปิดปั๊ม และลงบันทึก "หมดเวลา"
#    (เก็บเวลาที่เริ่มถามไว้ใน s แล้วเช็กทุกรอบด้วย time.ticks_diff)
